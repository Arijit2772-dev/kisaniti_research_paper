"""EXP-01 coverage summary for Paddy(Basmati), Punjab, from the filed raw CSVs.

Usage:  python3 layers/L1_data/coverage_basmati.py

Reads data/raw/agmarknet/paddy_basmati/*.csv (never modified) and writes:
  results/L1_coverage/basmati_by_month.csv
  results/L1_coverage/basmati_by_season.csv
  results/L1_coverage/basmati_by_variety.csv
  results/L1_coverage/basmati_coverage.md
Only observed rows are counted; blank-date rows are counted separately and not used.
Seasons run September to August (e.g. 2023-24 = Sep 2023 .. Aug 2024).
"""

import csv
import statistics
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw" / "agmarknet" / "paddy_basmati"
OUT = ROOT / "results" / "L1_coverage"


def season_of(day: datetime) -> str:
    start = day.year if day.month >= 9 else day.year - 1
    return f"{start}-{str(start + 1)[2:]}"


def read_rows(path: Path):
    market = None
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if line.startswith("Market Name :"):
            market = line.split(":", 1)[1].strip().strip(",")
            continue
        if not line or line.startswith(("Arrival Date", '"')) or market is None:
            continue
        fields = next(csv.reader([line]))
        if len(fields) != 6:
            continue
        if not fields[0].strip():
            yield {"blank": True}
            continue
        def number(text):
            # "-" means not reported: keep it as missing, never as zero
            try:
                return float(text)
            except ValueError:
                return None

        day = datetime.strptime(fields[0], "%d/%m/%Y")
        yield {
            "blank": False, "day": day, "market": market, "variety": fields[2].strip(),
            "arrivals": number(fields[1]), "min": number(fields[3]),
            "max": number(fields[4]), "modal": number(fields[5]),
        }


def summarise(rows):
    modal = [r["modal"] for r in rows if r["modal"] is not None]
    return {
        "rows": len(rows),
        "rows_missing_modal": sum(r["modal"] is None for r in rows),
        "rows_missing_min_or_max": sum(r["min"] is None or r["max"] is None for r in rows),
        "markets": len({r["market"] for r in rows}),
        "trading_days": len({r["day"] for r in rows}),
        "varieties": len({r["variety"] for r in rows}),
        "arrivals_tonnes": round(sum(r["arrivals"] or 0 for r in rows), 1),
        "modal_min": min(modal), "modal_median": statistics.median(modal), "modal_max": max(modal),
    }


def main() -> None:
    by_month, by_season, by_variety = defaultdict(list), defaultdict(list), defaultdict(list)
    blanks = defaultdict(int)
    for path in sorted(RAW.glob("*_punjab.csv")):
        month = path.name[:7]
        for row in read_rows(path):
            if row["blank"]:
                blanks[month] += 1
                continue
            by_month[month].append(row)
            by_season[season_of(row["day"])].append(row)
            by_variety[row["variety"]].append(row)

    OUT.mkdir(parents=True, exist_ok=True)
    def write(name, key, groups, extra=None):
        with (OUT / name).open("w", newline="") as handle:
            writer = csv.writer(handle)
            first = summarise(next(iter(groups.values())))
            header = [key] + list(first) + (["blank_date_rows"] if extra else [])
            writer.writerow(header)
            for k in sorted(groups):
                s = summarise(groups[k])
                writer.writerow([k] + list(s.values()) + ([extra.get(k, 0)] if extra else []))

    write("basmati_by_month.csv", "month", by_month, blanks)
    write("basmati_by_season.csv", "season", by_season)
    write("basmati_by_variety.csv", "variety", by_variety)

    total = [r for rows in by_month.values() for r in rows]
    lines = ["# Paddy(Basmati), Punjab: coverage of the filed AGMARKNET data", "",
             f"Generated by `layers/L1_data/coverage_basmati.py` from {len(by_month)} monthly files "
             f"({min(by_month)} to {max(by_month)}). Blank-date rows ({sum(blanks.values())}) are not counted.", "",
             f"**Total:** {len(total):,} observed rows, {len({r['market'] for r in total})} mandis, "
             f"{len({r['day'] for r in total})} trading days, {len({r['variety'] for r in total})} varieties; "
             f"modal price ₹{min(r['modal'] for r in total if r['modal'] is not None):,.0f} to ₹{max(r['modal'] for r in total if r['modal'] is not None):,.0f} per quintal "
             f"(median ₹{statistics.median(r['modal'] for r in total if r['modal'] is not None):,.0f}). "
             f"{sum(r['modal'] is None for r in total)} rows have no modal price and {sum(r['min'] is None or r['max'] is None for r in total)} lack a minimum or maximum (reported as '-' by AGMARKNET; kept, not filled).", "",
             "## By season", "", "| Season | Months filed | Rows | Mandis | Trading days | Modal ₹/q min / median / max |", "|---|---|---|---|---|---|"]
    months_in = defaultdict(int)
    for m in by_month:
        months_in[season_of(datetime.strptime(m + "-01", "%Y-%m-%d"))] += 1
    for s in sorted(by_season):
        x = summarise(by_season[s])
        lines.append(f"| {s} | {months_in[s]} | {x['rows']:,} | {x['markets']} | {x['trading_days']} | "
                     f"{x['modal_min']:,.0f} / {x['modal_median']:,.0f} / {x['modal_max']:,.0f} |")
    lines += ["", "## By variety", "", "| Variety | Rows | Mandis | Modal ₹/q min / median / max |", "|---|---|---|---|"]
    for v in sorted(by_variety, key=lambda k: -len(by_variety[k])):
        x = summarise(by_variety[v])
        lines.append(f"| {v} | {x['rows']:,} | {x['markets']} | {x['modal_min']:,.0f} / {x['modal_median']:,.0f} / {x['modal_max']:,.0f} |")
    lines += ["", "## By month", "", "| Month | Rows | Mandis | Blank-date rows |", "|---|---|---|---|"]
    for m in sorted(by_month):
        x = summarise(by_month[m])
        lines.append(f"| {m} | {x['rows']:,} | {x['markets']} | {blanks.get(m, 0)} |")
    (OUT / "basmati_coverage.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
