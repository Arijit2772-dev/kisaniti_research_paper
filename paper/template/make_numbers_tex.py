"""Write numbers_v2.tex (LaTeX macros) and ../tables/table_msp_share.tex from the v2 result
files, so no number in the section drafts is typed by hand.

    python3 paper/template/make_numbers_tex.py

Use a number in the text as \\kn{msp_share_2024}. A missing key prints as ??key?? in bold.
This bridges the legacy v2 results until paper/numbers.py (phase R0) reads the v3 results;
then point the loaders below at the new results and keep the macro names.
"""
from __future__ import annotations

import ast
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
EXP = ROOT / "legacy" / "v2_from_rp_kisan" / "experiments"
RES = EXP / "results"


def msp_table() -> dict[int, int]:
    """MSP_GRADE_A as written in the forecasting script (official DES values)."""
    tree = ast.parse((EXP / "forecast_experiment.py").read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "MSP_GRADE_A" for t in node.targets):
            return ast.literal_eval(node.value)
    raise RuntimeError("MSP_GRADE_A not found")


def main() -> None:
    fr = json.loads((RES / "forecast_results.json").read_text())
    d = fr["description"]
    msp = msp_table()
    seasons = sorted(int(s) for s in d["dates_per_season"])
    n_mandis = sum(1 for _ in open(EXP / "mandi_coordinates.csv")) - 1

    k: dict[str, str] = {
        "mandis": str(n_mandis),
        "season_first": str(seasons[0]),
        "season_last": str(seasons[-1]),
        "trading_dates": str(d["trading_dates"]),
        "observed_mandi_days": f"{d['observed_mandi_days']:,}",
        "observed_share": f"{100 * d['observed_share']:.1f}",
    }
    shares = {s: 100 * d["share_exactly_at_msp_by_season"][str(s)] for s in seasons}
    for s in seasons:
        k[f"msp_{s}"] = f"{msp[s]:,}"
        k[f"msp_share_{s}"] = f"{shares[s]:.1f}"
        k[f"price_sd_{s}"] = f"{d['price_std_by_season'][str(s)]:.1f}"
        k[f"cross_sd_{s}"] = f"{d['cross_mandi_daily_std_mean_by_season'][str(s)]:.1f}"
    s_min = min(shares, key=shares.get)
    k["msp_share_min"] = f"{shares[s_min]:.1f}"
    k["msp_share_min_season"] = str(s_min)

    with open(RES / "forecast_table.csv") as f:
        rows = {r["Model"]: r for r in csv.DictReader(f)}
    short = {"Naive (last price)": "naive", "Moving average (7 dates)": "movavg", "MSP rule": "msp",
             "Ridge regression": "ridge", "GRU (no graph)": "gru",
             "T-GCN (graph, no attention)": "tgcn", "A3T-GCN": "atgcn"}
    for name, key in short.items():
        k[f"mae_{key}_mean"] = f"{float(rows[name]['MAE mean']):.2f}"
        for s in ("2023", "2024", "2025"):
            k[f"mae_{key}_{s}"] = f"{float(rows[name][f'MAE {s}']):.2f}"
    folds = fr["folds"]
    k["test_seasons"] = ", ".join(sorted(folds))
    paired = {m: [0, 0, 0] for m in ("A3T-GCN", "MSP rule")}
    for f in folds.values():
        for m in paired:
            p = f["extra"]["paired_vs_naive_h1"][m]
            paired[m][0] += p["dates_better_than_naive"]
            paired[m][1] += p["dates_worse"]
            paired[m][2] += p["ties"]
    k["paired_dates"] = str(sum(paired["A3T-GCN"]))
    k["paired_atgcn_worse"] = str(paired["A3T-GCN"][1])
    k["paired_msp_better"], k["paired_msp_worse"], k["paired_msp_ties"] = map(str, paired["MSP rule"])

    lines = ["% Generated by make_numbers_tex.py from legacy/v2_from_rp_kisan/experiments/results.",
             "% Do not edit by hand.",
             r"\providecommand\kn[1]{\ifcsname kn@#1\endcsname\csname kn@#1\endcsname"
             r"\else\textbf{??\detokenize{#1}??}\fi}"]
    lines += [rf"\expandafter\def\csname kn@{key}\endcsname{{{val}}}" for key, val in sorted(k.items())]
    (HERE / "numbers_v2.tex").write_text("\n".join(lines) + "\n")

    t = ["% Generated by paper/template/make_numbers_tex.py. Do not edit by hand.",
         r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"Season & MSP Grade A & Trading & Prices equal & SD of \\",
         r" & (Rs/q) & dates & to MSP (\%) & prices (Rs/q) \\", r"\midrule"]
    for s in seasons:
        t.append(rf"{s} & {msp[s]:,} & {d['dates_per_season'][str(s)]} & {shares[s]:.1f} & "
                 rf"{d['price_std_by_season'][str(s)]:.1f} \\")
    t += [r"\bottomrule", r"\end{tabular}"]
    tables = ROOT / "paper" / "tables"
    tables.mkdir(exist_ok=True)
    (tables / "table_msp_share.tex").write_text("\n".join(t) + "\n")
    print(f"wrote {len(k)} macros and table_msp_share.tex")


if __name__ == "__main__":
    main()
